const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const root = path.resolve(__dirname, "..");
const arg = process.argv.find(x => x.startsWith("--run-date="));
const runIso = arg ? arg.split("=")[1] : new Intl.DateTimeFormat("en-CA", { timeZone: "America/New_York", year: "numeric", month: "2-digit", day: "2-digit" }).format(new Date());
const run = new Date(`${runIso}T12:00:00-04:00`);
if (run.getDay() !== 1) throw new Error(`${runIso} is not a Monday in Eastern time`);
const issue = new Date(run); issue.setDate(issue.getDate() + 2);
const iso = issue.toISOString().slice(0, 10);
const week = Math.ceil(issue.getDate() / 7);
const rotations = { 1: ["Local Business Spotlight", "Homeowner / Seasonal Home Tip"], 2: ["Recipe", "Local Community Event"], 3: ["Local History", "Seasonal Home Maintenance"], 4: ["Restaurant / Coffee Shop / Community Spotlight", "Weekend Idea"], 5: ["Non-repetitive local/community feature", "Non-repetitive lifestyle feature"] };
const issueFile = path.join(root, `${iso}.json`);
if (!fs.existsSync(issueFile)) throw new Error(`Content research is required before generation. Create ${issueFile} for rotation: ${rotations[week].join(" + ")}`);
execFileSync(process.execPath, [path.join(__dirname, "prepare-root-issue.js"), iso], { stdio: "inherit" });
execFileSync(process.execPath, [path.join(root, "generate.js")], { stdio: "inherit" });
execFileSync(process.execPath, [path.join(__dirname, "verify-root-newsletter.js"), `--issue=${iso}`], { stdio: "inherit" });
execFileSync(process.execPath, [path.join(__dirname, "newsletter-approval.js"), "prepare", `--issue=${iso}`], { stdio: "inherit" });
console.log(JSON.stringify({ runDate: runIso, issueDate: iso, rotation: rotations[week], subscriberDistribution: false, automaticAssistantHandoff: false }, null, 2));
